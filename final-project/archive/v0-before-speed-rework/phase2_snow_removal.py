#!/usr/bin/env python3
"""
ECSE 211 Final Design Project - Phase 2: Autonomous Snow Removal
================================================================
Mission Procedure (<= 120 seconds):
  1. Loads the street topology saved by Phase 1 from `street_map.json`.
  2. Departs from Origin (0,0), steps onto Tile (0,0) center, and navigates
     to the street entrance between s1 and s2.
  3. Activates the front intake roller (Port D) and sweeps the entire mapped
     street corridor along tile centerlines with zero wall contact:
     - Uses spatial-windowed line squaring at tile boundaries (ignoring pom-poms).
  4. Navigates from the street exit to the drop-off tile bordering (d1, d2).
  5. Aligns with the table edge and actuates the discharge mechanism (Port A)
     to deposit all collected pom-poms into the table-height bucket.
  6. Returns autonomously to Origin (0,0) before the 120s deadline.
"""

import json
import os
import time
from snowplow_core import (
    CRUISE_DPS,
    HEADING_TO_DELTA,
    MAP_FILE,
    SWEEP_DPS,
    drive_straight_distance,
    dump_snow_payload,
    init_hardware,
    navigate_tile_with_obstacle_avoidance,
    reset_brick,
    should_abort_for_time,
    start_intake_roller,
    step_one_tile_center,
    step_origin_to_start_tile,
    step_tile_to_origin,
    stop_all_motors,
    stop_intake_roller,
    turn_to,
)

# Dump positioning mode at the (d1, d2) table edge:
#   "SIDE_OVER_FRONT"     -> Robot faces bucket, steps forward so front container overhangs bucket,
#                            and Motor A tips the container 90°-110° sideways into the bucket.
#   "SIDE_PARALLEL_RIGHT" -> Robot parks parallel to table edge with its RIGHT side facing the bucket,
#                            and Motor A tips the container 90°-110° to the right off the edge.
#   "SIDE_PARALLEL_LEFT"  -> Robot parks parallel to table edge with its LEFT side facing the bucket,
#                            and Motor A tips the container 90°-110° to the left off the edge.
#   "REAR"                -> Robot backs up to the edge and dumps off the rear.
DUMP_MODE = "SIDE_OVER_FRONT"
EDGE_APPROACH_OFFSET_CM = 7.0  # Distance (cm) from tile center toward table edge for clean bucket drop


def load_street_map() -> dict:
    """Loads street_map.json generated by Phase 1."""
    if not os.path.exists(MAP_FILE):
        raise FileNotFoundError(
            f"Map file '{MAP_FILE}' not found! Run phase1_mapping.py first."
        )
    with open(MAP_FILE, "r") as f:
        data = json.load(f)
    print(f"[LOAD] Loaded map from '{MAP_FILE}' ({len(data['street_tiles'])} street tiles).")
    return data


def heading_between_adjacent_tiles(t_from: tuple[int, int], t_to: tuple[int, int]) -> int:
    """Returns cardinal heading (0, 90, 180, 270) from tile t_from to adjacent tile t_to."""
    dx = t_to[0] - t_from[0]
    dy = t_to[1] - t_from[1]
    for h, delta in HEADING_TO_DELTA.items():
        if delta == (dx, dy):
            return h
    raise ValueError(f"Tiles {t_from} and {t_to} are not cardinally adjacent!")


def execute_table_edge_dump(dropoff_tile: tuple[int, int], outward_edge_heading: int):
    """
    Positions the robot at `dropoff_tile` along the table edge (d1, d2) according to DUMP_MODE,
    rotates the container 90°-110° via Motor A to dump into the bucket, and returns
    the wheel axle to the center of `dropoff_tile`.
    """
    print(
        f"\n[DROP-OFF] Aligning at Drop-Off Tile {dropoff_tile} "
        f"(Bucket edge: {outward_edge_heading}°, Mode: {DUMP_MODE})..."
    )

    if DUMP_MODE == "SIDE_OVER_FRONT":
        # Face bucket directly, step forward so front container overhangs the open bucket,
        # tip container 90°-110° sideways, then reverse back to tile center.
        align_heading = float(outward_edge_heading % 360)
        turn_to(align_heading)
        drive_straight_distance(EDGE_APPROACH_OFFSET_CM, forward=True, hold_heading=align_heading, speed_dps=SWEEP_DPS)
        dump_snow_payload()
        drive_straight_distance(EDGE_APPROACH_OFFSET_CM, forward=False, hold_heading=align_heading, speed_dps=SWEEP_DPS)

    elif DUMP_MODE == "SIDE_PARALLEL_RIGHT":
        # Step toward bucket edge, then turn -90° (CCW) so the robot's RIGHT side overhangs the bucket
        edge_heading = float(outward_edge_heading % 360)
        parallel_heading = float((outward_edge_heading - 90) % 360)
        turn_to(edge_heading)
        drive_straight_distance(EDGE_APPROACH_OFFSET_CM, forward=True, hold_heading=edge_heading, speed_dps=SWEEP_DPS)
        turn_to(parallel_heading)
        dump_snow_payload()
        turn_to(edge_heading)
        drive_straight_distance(EDGE_APPROACH_OFFSET_CM, forward=False, hold_heading=edge_heading, speed_dps=SWEEP_DPS)

    elif DUMP_MODE == "SIDE_PARALLEL_LEFT":
        # Step toward bucket edge, then turn +90° (CW) so the robot's LEFT side overhangs the bucket
        edge_heading = float(outward_edge_heading % 360)
        parallel_heading = float((outward_edge_heading + 90) % 360)
        turn_to(edge_heading)
        drive_straight_distance(EDGE_APPROACH_OFFSET_CM, forward=True, hold_heading=edge_heading, speed_dps=SWEEP_DPS)
        turn_to(parallel_heading)
        dump_snow_payload()
        turn_to(edge_heading)
        drive_straight_distance(EDGE_APPROACH_OFFSET_CM, forward=False, hold_heading=edge_heading, speed_dps=SWEEP_DPS)

    elif DUMP_MODE == "REAR":
        # Point robot's REAR toward the bucket edge, back up slightly, dump, then pull forward
        align_heading = float((outward_edge_heading + 180) % 360)
        turn_to(align_heading)
        drive_straight_distance(EDGE_APPROACH_OFFSET_CM, forward=False, hold_heading=align_heading, speed_dps=SWEEP_DPS)
        dump_snow_payload()
        drive_straight_distance(EDGE_APPROACH_OFFSET_CM, forward=True, hold_heading=align_heading, speed_dps=SWEEP_DPS)


def run_phase2():
    print("=" * 65)
    print("  ECSE 211 FINAL PROJECT - PHASE 2: WINTER SNOW REMOVAL")
    print("=" * 65)

    map_data = load_street_map()
    approach_tile = tuple(map_data["approach_tile"])
    street_tiles = [tuple(t) for t in map_data["street_tiles"]]
    blocked_tiles = {tuple(t) for t in map_data.get("blocked_tiles", [])}
    blocked_tiles.difference_update(street_tiles)
    dropoff_tile = tuple(map_data["dropoff_tile"])
    dropoff_heading = int(map_data["dropoff_heading"])

    print(f"  Entrance Approach Tile: {approach_tile}")
    print(f"  Mapped Street Route ({len(street_tiles)} tiles): {street_tiles}")
    print(f"  Drop-Off Tile: {dropoff_tile} (Edge Heading: {dropoff_heading}°)")
    input("Place robot at Origin (0,0) facing +Y (North) and press Enter to start Phase 2...")

    init_hardware()
    phase_start_time = time.time()

    # 1. Step from Origin (0,0) intersection onto Tile (0,0) center
    current_tile = (0, 0)
    step_origin_to_start_tile(current_tile)

    # 2. Navigate to the street entrance approach tile
    print(f"\n[NAV] Navigating to Entrance Approach Tile {approach_tile}...")
    current_tile = navigate_tile_with_obstacle_avoidance(
        current_tile, approach_tile, blocked_tiles, speed_dps=CRUISE_DPS, check_obstacles=False
    )

    # 3. Activate intake roller and sweep the mapped street corridor
    start_intake_roller()
    print(f"\n[SWEEP] Sweeping {len(street_tiles)} street tiles at {SWEEP_DPS} dps...")

    for idx, next_street_tile in enumerate(street_tiles):
        if should_abort_for_time(phase_start_time, current_tile):
            print("[WATCHDOG] Stopping sweep early to guarantee drop-off & return within 120s!")
            break

        step_heading = heading_between_adjacent_tiles(current_tile, next_street_tile)
        print(f"  -> Sweeping step {idx + 1}/{len(street_tiles)}: {current_tile} -> {next_street_tile} ({step_heading}°)")
        current_tile = step_one_tile_center(
            current_tile, step_heading, speed_dps=SWEEP_DPS, enable_line_square=True
        )

    # Brief pause to let final pom-poms clear the roller into the hopper
    time.sleep(0.4)
    stop_intake_roller()

    # 4. Navigate from street exit to Drop-Off Tile (d1, d2)
    print(f"\n[NAV] Navigating from Tile {current_tile} to Drop-Off Tile {dropoff_tile}...")
    current_tile = navigate_tile_with_obstacle_avoidance(
        current_tile, dropoff_tile, blocked_tiles, speed_dps=CRUISE_DPS, check_obstacles=True
    )

    # 5. Deposit snow into table-height bucket at (d1, d2)
    execute_table_edge_dump(dropoff_tile, dropoff_heading)

    # 6. Return to Origin (0,0)
    print(f"\n[RETURN] Navigating from Drop-Off Tile {current_tile} back to Origin (0,0)...")
    current_tile = navigate_tile_with_obstacle_avoidance(
        current_tile, (0, 0), blocked_tiles, speed_dps=CRUISE_DPS, check_obstacles=True
    )
    step_tile_to_origin()

    total_time = time.time() - phase_start_time
    print("\n" + "=" * 65)
    print(f"  PHASE 2 COMPLETE in {total_time:.1f}s (Limit: 120.0s)!")
    print("=" * 65)


if __name__ == "__main__":
    try:
        run_phase2()
    except (KeyboardInterrupt, SystemExit, BaseException) as e:
        print(f"\n[PHASE 2 TERMINATED]: {e}")
    finally:
        stop_all_motors()
        reset_brick()
